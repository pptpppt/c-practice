#include <stdio.h>

/* 在这片区域定义需要的类型和函数原型 */


int main(void) {

    /* 任务 1：写一个巡检报告
     * 用 fprintf 写三行到 report.txt：
     *     A棚 温度28度 湿度62.5%
     *     B棚 温度31度 湿度35.0%
     *     C棚 温度19度 湿度88.0%
     * 写完 fclose，然后去资源管理器里双击 report.txt 看一眼真的有了。
     * 注意：%% 才是百分号本体，忘了的话格式串会出错。
     */


    /* 任务 2：fopen 失败的样子（重要）
     * 故意用一个不存在的路径打开读：fopen("no_such_folder/x.txt", "r")
     * 观察 fp 是不是 NULL，并打印提示后 return 1。
     * 记住这个判断模式，以后所有文件操作都要有：
     *     FILE *fp = fopen(path, "r");
     *     if (fp == NULL) { printf("打不开 %s\n", path); return 1; }
     */


    /* 任务 3：fscanf 读回来
     * 打开任务 1 生成的 report.txt，用 fscanf 循环读出三行并打印。
     * 循环条件写：while (fscanf(fp, " %c棚 温度%d度 湿度%f%%", &shed,&temp,&humi) == 3)
     * 关键：那个 == 3 是「成功读到三项」，也是循环的终止条件。
     * 试试改成 while (... != EOF) 会怎样 —— 大概率会多读一次脏数据。
     */


    /* 任务 4：fgets + sscanf 拆行（推荐套路）
     * 对同一个 report.txt，改用：
     *     char line[256];
     *     while (fgets(line, sizeof(line), fp) != NULL) {
     *         用 sscanf(line, ...) 拆出三个值
     *     }
     * 顺便打印 printf("[%s]", line) 看看 —— 换行符是不是被读进来了？
     * 体会为什么推荐这套：整行拿回来慢慢拆，比 fscanf 硬凑格式串容错得多。
     */


    /* 任务 5：追加写 "a"（别忘了 "w" 会清空）
     * 先用 "w" 写一行 "第一条"，fclose。
     * 再用 "w" 写一行 "第二条"，fclose，打开文件看 —— 只剩第二条！
     * 改用 "a" 再写一行 "第三条"，再看 —— 两条都在了。
     * 这个实验必须亲手做一次，"w" 清空数据是很多人丢数据的原因。
     */


    /* 任务 6（★）：故意写错，认识四种雷
     * 一次只试一处：
     *     FILE *fp = fopen("x.txt","r"); fprintf(fp,"hi");      // 读模式写 → 崩溃
     *     FILE *fp = fopen("x.txt","w"); 用完不 fclose           // 内容可能没落盘
     *     fscanf(fp, "%d", temp);                               // 忘了 & → 段错误
     *     while (!feof(fp)) { fscanf(...); 处理; }              // 最后一行会被处理两次
     * 第四条最隐蔽：跑到最后一行时还没 EOF，读失败后循环体照样执行了一遍。
     */


    /* 任务 7（★★）：真正的日报生成器（今天的收官，也是 c16 的预演）
     * 程序要干三件事：
     *   ① 从键盘循环读入若干条记录（棚号 温度 湿度，输入 '#' 结束），存进 Sensor 数组
     *   ② 把录入的数据写成文件 patrol.txt，每行一条：
     *          A 28 62.5
     *   ③ 再打开 patrol.txt 读回来，解析并打印一份带判定的日报：
     *          A棚 温度28度 湿度62.5% 判定：维持现状
     *          判定规则用 c02 那套：高温>=35 / 低温<10 / 又热又干要灌溉 / 过湿要停
     * 工程要求：
     *     - Sensor 结构体定义在 main 外面
     *     - 至少抽 3 个函数：input_data / save_to_file / load_and_report
     *     - 所有 fopen 都要判 NULL
     * 门槛：做完这个，你就有了「完整数据管线」的雏形：
     *       输入 → 内存（结构体数组）→ 落盘 → 再读出来 → 出报告。
     *       c16/c17 要做的就是这个的加强版。
     */


    return 0;
}
