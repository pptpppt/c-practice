/* ---------------- 模范示例 0：先建立画面感 --------------------------------
 * 内存是一条长街，每个格子有门牌号（地址），格子里面放着数据。
 *
 *     int temp = 28;
 *
 * 想象 temp 住在 0x60FEE0 号房间，房间里写着 28。
 *   - &temp  → 拿到门牌号     0x60FEE0（取地址）
 *   - 通过门牌号能找到房间里的东西
 *
 * 指针变量就是「专门用来存门牌号的变量」。
 * ------------------------------------------------------------------------- */

/* ---------------- 模范示例 1：& 与 * --------------------------------------
#include <stdio.h>

int main(void) {
    int temp = 28;

    printf("temp 的值   ：%d\n", temp);
    printf("temp 的地址 ：%p\n", (void *)&temp);     // %p 打印地址，要转 void*

    int *p = &temp;              // p 里放着 temp 的地址
    printf("p 里存的地址：%p\n", (void *)p);
    printf("顺着 p 找到的值：%d\n", *p);              // *p 是「解引用」

    *p = 31;                     // 通过指针改房间里的东西
    printf("改完后 temp ：%d\n", temp);               // temp 真变了！
    return 0;
}
 *
 * 两个符号，背下来：
 *     &  取地址 —— 问：它住哪？
 *     *  解引用 —— 顺着地址去找人（或者改房间里的东西）
 *
 * 声明里的 int *p 读成「p 是一个指针，指向 int」。
 * ------------------------------------------------------------------------- */

/* ---------------- 模范示例 2：为什么 scanf 要写 & -------------------------
 * 回顾 c01 就一直在用：
 *     scanf("%d", &temp);
 *
 * 现在能解释了：scanf 是个函数，它要往你的 temp 里写值。
 * 但值传递改不了外面的变量（c05 任务 5 的结论），
 * 所以只能把 temp 的地址给它 —— 它顺着地址找到那间房，直接往里写。
 *
 * 这也是 c09「用指针突破值传递」的同一个套路。
 * ------------------------------------------------------------------------- */

/* ---------------- 模范示例 3：指针变量本身也有大小 ------------------------
#include <stdio.h>

int main(void) {
    int a = 1;
    char c = 'A';
    double d = 3.14;

    int    *pa = &a;
    char   *pc = &c;
    double *pd = &d;

    printf("sizeof(pa) = %zu\n", sizeof(pa));   // 都是 8（64 位系统）
    printf("sizeof(pc) = %zu\n", sizeof(pc));   // 也是 8
    printf("sizeof(pd) = %zu\n", sizeof(pd));   // 还是 8
    return 0;
}
 *
 * 结论：指针的大小跟它指向的类型无关 —— 门牌号的长度是一样的。
 * 但类型决定了「顺着门牌号进去能读几个格子」（下一个示例就看到差别）。
 * ------------------------------------------------------------------------- */

/* ---------------- 模范示例 4：NULL 与野指针 --------------------------------
 *     int *p = NULL;      // 空指针：明确表示「现在不指向任何地方」
 *
 * 野指针：声明了但没赋值就使用。
 *     int *p;  *p = 5;    // p 里是随机垃圾地址，往那里写 = 程序崩溃
 *
 * 好习惯：声明时就赋 NULL，用之前判断一下。
 *     if (p != NULL) { printf("%d", *p); }
 *
 * -Wall 会对「未初始化就使用」给警告，这就是为什么编译命令里必须有它。
 * ------------------------------------------------------------------------- */

/* ====================== 下面是今天可直接编译运行的版本 ===================== */
#include <stdio.h>

int main(void) {
    int temp = 28;

    printf("---- 指针基础演示 ----\n");
    printf("temp 的值      ：%d\n", temp);
    printf("temp 的地址    ：%p\n", (void *)&temp);

    int *p = &temp;
    printf("p 存着的地址   ：%p\n", (void *)p);
    printf("*p 取到的值    ：%d\n", *p);
    printf("p 自己的大小   ：%zu 字节\n", sizeof(p));

    printf("\n---- 通过指针改值 ----\n");
    *p = 31;
    printf("用 *p = 31 之后，temp = %d\n", temp);

    printf("\n---- 多个变量对比 ----\n");
    char c = 'A';
    double d = 3.14;
    char   *pc = &c;
    double *pd = &d;
    printf("char*   解引用：%c\n", *pc);
    printf("double* 解引用：%.2f\n", *pd);

    printf("\n---- 空指针 ----\n");
    int *pn = NULL;
    printf("pn = %p", (void *)pn);
    printf("  （0 表示不指向任何地方）\n");

    return 0;
}
