/* ---------------- 模范示例 1：关系运算符与逻辑运算符 ----------------------
 * 关系运算（结果是「真假」，C 里用 1 和 0 表示）：
 *     ==  等于       !=  不等于      >  大于      <  小于
 *     >=  大于等于   <=  小于等于
 *
 * 逻辑运算（把多个条件拼起来）：
 *     &&  并且（两边都真才真）      ||  或者（一边真就真）      !  非（取反）
 *
 * 一句话记住：== 是比较，= 是赋值。这两个搞混是 C 最常见的错误，没有之一。
 *
 * printf("%d\n", 25 > 20);   → 1
 * printf("%d\n", 25 == 20);  → 0
 * printf("%d\n", 25 = 20);   → 编译报错！= 是赋值，不能拿来做判断
 * ------------------------------------------------------------------------- */

/* ---------------- 模范示例 2：if / else if / else -------------------------
#include <stdio.h>

int main(void) {
    int temp = 38;

    if (temp >= 35) {
        printf("高温报警，开顶窗\n");
    } else if (temp < 10) {
        printf("低温报警，关棚膜\n");
    } else {
        printf("温度正常\n");
    }
    return 0;
}

要点：
  ① 条件必须写在圆括号里，不能省；圆括号后面不能加分号
  ② if (temp > 35);  ← 这个分号是灾难：分号本身就是一条空语句，
     等于「如果温度大于35，什么都不做」，下面的 printf 会无条件执行
  ③ 大括号只有一条语句时可以省，但新手一律写上，省了迟早踩 else 悬空的坑
  ④ 从上往下判断，命中一个就跳出整个结构，所以条件的顺序要讲究
 * ------------------------------------------------------------------------- */

/* ---------------- 模范示例 3：复合条件（&& || !）--------------------------
#include <stdio.h>

int main(void) {
    int   temp = 28;
    float humi = 35.0f;

    if (temp > 25 && humi < 40) {        // 又热又干 → 灌
        printf("启动灌溉\n");
    } else if (temp < 5 || humi > 85) {  // 太冷 或 太湿 → 停
        printf("暂停作业\n");
    } else {
        printf("维持现状\n");
    }
    return 0;
}

坑：&& 和 || 写成单个 & 和 | —— 那是按位运算，语义完全不同，
    而且它不会报错，只是结果不对，属于最难查的一类 bug。
 * ------------------------------------------------------------------------- */

/* ---------------- 模范示例 4：switch（多档位选择）-------------------------
#include <stdio.h>

int main(void) {
    int mode = 0;
    printf("请选择作业模式（1耕地 2播种 3收获）：");
    if (scanf("%d", &mode) != 1) { printf("输入错误\n"); return 1; }

    switch (mode) {
        case 1:  printf("耕地模式：低速大扭矩\n");  break;
        case 2:  printf("播种模式：中速恒定\n");    break;
        case 3:  printf("收获模式：高速\n");        break;
        default: printf("没有这个模式\n");          break;
    }
    return 0;
}

要点：
  ① switch 只能判断「整数/字符是否等于某个值」，判断范围（> <）只能用 if
  ② 每个 case 后面的 break 不能漏：漏掉会「穿透」到下一个 case 继续执行
  ③ default 写不写都行，但写上能兜住非法输入
  ④ case 后面是常量，不能写 case temp > 20: 这种
 * ------------------------------------------------------------------------- */

/* ---------------- 模范示例 5：三目运算符 ?: ------------------------------
 * 语法：  条件 ? 成立时的值 : 不成立时的值
 *
 *     int hot = (temp_a > temp_b) ? temp_a : temp_b;   // 取两棚较高温
 *
 * 等价于 if/else 的四行写法，适合「二选一赋一个值」这种简单场景。
 * 条件一复杂就别用它，可读性会崩。
 * ------------------------------------------------------------------------- */

/* ---------------- 模范示例 6：浮点数千万别用 == 比较 ---------------------
 * float 存的是近似值，0.1 这种数在内存里根本不精确。
 *     if (humi == 62.5)   ← 可能永远不成立
 * 正确写法：判断两个数的差是不是足够小
 *     if (fabs(humi - 62.5) < 0.001)      // 需要 #include <math.h>
 * 编译时要加 -lm：gcc -Wall -g xxx.c -o xxx.exe -lm
 * 现阶段先记住这条结论，别拿 == 比小数。
 * ------------------------------------------------------------------------- */

/* ====================== 下面是今天可直接编译运行的版本 ===================== */
#include <stdio.h>

int main(void) {
    int   temp = 0;
    float humi = 0.0f;

    printf("请输入温度(整数)和湿度(小数)，用空格分开：");
    if (scanf("%d %f", &temp, &humi) != 2) {
        printf("输入格式不对\n");
        return 1;
    }

    printf("---- 巡检结论 ----\n");

    /* 温度部分：三档 */
    if (temp >= 35) {
        printf("温度 %d 度：高温，开顶窗通风\n", temp);
    } else if (temp < 10) {
        printf("温度 %d 度：低温，关棚膜保温\n", temp);
    } else {
        printf("温度 %d 度：正常\n", temp);
    }

    /* 湿度部分：复合条件 */
    if (temp > 25 && humi < 40.0f) {
        printf("湿度 %.1f%%：偏干，启动灌溉\n", humi);
    } else if (humi > 85.0f) {
        printf("湿度 %.1f%%：过湿，停止灌溉\n", humi);
    } else {
        printf("湿度 %.1f%%：适宜\n", humi);
    }

    return 0;
}
